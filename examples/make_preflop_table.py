r"""Regenerate the two preflop equity tables.

Run:
    .venv\Scripts\python examples\make_preflop_table.py           (both tables)
    .venv\Scripts\python examples\make_preflop_table.py random    (table 1 only)
    .venv\Scripts\python examples\make_preflop_table.py ranges    (table 2 only)

1. ``src/nutsfinder/engine/preflop_data.py``: each of the 169 classes against
   a uniformly random hand, 100,000 samples each (SE below 0.16 points).
   About 3 minutes.
2. ``src/nutsfinder/engine/preflop_range_data.py``: each class against the
   top x% of hands for every x in ``RANGE_GRID``, 5,000 samples each (SE
   below 0.71 points). About 2.5 minutes.

Table 2 depends on table 1 (the "top x%" ranges come from the ranking in
table 1), and Python reads table 1 when ``nutsfinder.engine.preflop`` is
first imported. So after writing table 1 the script runs itself again in a
fresh process to build table 2 from the new ranking.
"""

from __future__ import annotations

import subprocess
import sys
import time
from pathlib import Path

from nutsfinder.engine.preflop import ALL_CLASSES, compute_preflop_table, compute_range_table

RANDOM_SAMPLES = 100_000
RANGE_SAMPLES = 5_000
SEED = 20261116
ENGINE = Path(__file__).resolve().parent.parent / "src" / "nutsfinder" / "engine"


def write_random_table() -> None:
    start = time.perf_counter()
    table = compute_preflop_table(RANDOM_SAMPLES, SEED)
    lines = [
        '"""Preflop equity of each hand class against a uniformly random hand.',
        "",
        "Generated by examples/make_preflop_table.py: do not edit by hand.",
        f"{RANDOM_SAMPLES:,} Monte Carlo samples per class, seeds {SEED} + class index.",
        "Each entry is (equity, standard error).",
        '"""',
        "",
        "PREFLOP_TABLE: dict[str, tuple[float, float]] = {",
    ]
    lines += [f'    "{cls}": ({table[cls][0]:.5f}, {table[cls][1]:.5f}),' for cls in ALL_CLASSES]
    lines += ["}", ""]
    (ENGINE / "preflop_data.py").write_text("\n".join(lines))
    worst = max(se for _, se in table.values())
    print(f"table 1 written in {time.perf_counter() - start:.0f} s; largest SE {worst * 100:.3f} points")


def write_range_table() -> None:
    start = time.perf_counter()
    table = compute_range_table(RANGE_SAMPLES, SEED)
    lines = [
        '"""Preflop equity of each hand class against the top x% of hands.',
        "",
        "Generated by examples/make_preflop_table.py: do not edit by hand.",
        "Row = class; entry j = (equity, standard error) against the top",
        "RANGE_GRID[j] of hands (every grid width except 100%, which is in",
        f"preflop_data.py). {RANGE_SAMPLES:,} Monte Carlo samples per entry,",
        f"seed {SEED} + 100 * class index + j.",
        '"""',
        "",
        "PREFLOP_VS_TOP: dict[str, tuple[tuple[float, float], ...]] = {",
    ]
    for cls in ALL_CLASSES:
        row = ", ".join(f"({eq:.4f}, {se:.4f})" for eq, se in table[cls])
        lines.append(f'    "{cls}": ({row}),')
    lines += ["}", ""]
    (ENGINE / "preflop_range_data.py").write_text("\n".join(lines))
    worst = max(se for row in table.values() for _, se in row)
    print(f"table 2 written in {time.perf_counter() - start:.0f} s; largest SE {worst * 100:.3f} points")


def main() -> None:
    which = sys.argv[1] if len(sys.argv) > 1 else "both"
    if which in ("random", "both"):
        write_random_table()
    if which == "both":
        subprocess.run([sys.executable, __file__, "ranges"], check=True)  # fresh import of table 1
    if which == "ranges":
        write_range_table()


if __name__ == "__main__":
    main()
