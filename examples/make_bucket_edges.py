r"""Generate the postflop bucket edges (and the exact flop E[HS] tables).

Run:
    .venv\Scripts\python examples\make_bucket_edges.py            (everything, ~1 min on 24 cores)
    .venv\Scripts\python examples\make_bucket_edges.py --workers 1  (single core, ~3 min)

1. Every canonical turn board's exact E[HS] table (16,432 boards, ~9 ms each),
   in a process pool. Each table is a pure function of its board, so the
   result does not depend on the number of workers.
2. Every canonical flop's table (mean of its 49 turn tables), written to
   ``src/nutsfinder/abstraction/data/flop_ehs.npz`` (uint16, see
   :mod:`nutsfinder.abstraction.cards`). The file is optional: without it
   flop tables are computed on first use (~0.45 s per new flop).
3. ``SAMPLES`` uniformly random (hole, board) pairs per street from
   :func:`~nutsfinder.abstraction.cards.sample_deals` (seeded by hashing
   ``("sample_deals", street, SEED)``), their exact E[HS], and the
   equal-frequency edges for ``BUCKETS`` buckets, written to
   ``src/nutsfinder/abstraction/bucket_data.py``.
"""

from __future__ import annotations

import argparse
import os
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np

from nutsfinder.abstraction.cards import (
    FLOP_FILE, EHSTables, equal_frequency_edges, sample_deals, turn_table_exact,
)

SAMPLES = 100_000
BUCKETS = 50
SEED = 61  # hashed with the purpose, so it cannot collide with other streams
OUT = Path(__file__).resolve().parent.parent / "src" / "nutsfinder" / "abstraction" / "bucket_data.py"


def compute_turn_tables(workers: int, tables: EHSTables | None = None) -> EHSTables:
    """Fill every canonical turn table (step 1 above); also used by examples/train_holdem.py."""
    tables = tables if tables is not None else EHSTables(flop_file=None)
    start = time.perf_counter()
    turns = tables.all_canonical_turns()
    if workers > 1:
        with Pool(workers) as pool:
            results = pool.map(turn_table_exact, turns, chunksize=64)
    else:
        results = [turn_table_exact(t) for t in turns]
    tables.turn.update(zip(turns, results))
    print(f"{len(turns)} turn tables in {time.perf_counter() - start:.0f} s")
    return tables


def fill_tables(workers: int) -> EHSTables:
    tables = compute_turn_tables(workers)
    start = time.perf_counter()
    tables.compute_all_flops()
    tables.save_flops(FLOP_FILE)
    size = FLOP_FILE.stat().st_size / 1e6
    print(f"{len(tables.flop)} flop tables in {time.perf_counter() - start:.0f} s -> {FLOP_FILE} ({size:.1f} MB)")
    return tables


def street_edges(tables: EHSTables, street: int) -> tuple[float, ...]:
    start = time.perf_counter()
    values = [tables.ehs(h, b) for h, b in sample_deals(street, SAMPLES, SEED)]
    edges = equal_frequency_edges(values, BUCKETS)
    counts = np.bincount(np.searchsorted(edges, values, side="right"), minlength=BUCKETS)
    share = counts / SAMPLES
    print(f"street {street}: {time.perf_counter() - start:.0f} s; bucket share "
          f"{share.min():.4f}..{share.max():.4f} (target {1 / BUCKETS:.4f}); "
          f"distinct E[HS] values {len(set(values))}")
    return edges


def write_module(edges: dict[int, tuple[float, ...]]) -> None:
    lines = [
        '"""Equal-frequency E[HS] bucket edges for the flop, turn and river.',
        "",
        "Generated by examples/make_bucket_edges.py: do not edit by hand.",
        f"{SAMPLES:,} uniformly random (hole, board) pairs per street",
        f'(``sample_deals(street, {SAMPLES}, {SEED})``), exact E[HS] on the 1/65534 grid,',
        f"{BUCKETS} buckets: bucket = bisect_right(EDGES[street], ehs).",
        '"""',
        "",
        f"SAMPLES = {SAMPLES}",
        f"SEED = {SEED}",
        "",
        "EDGES: dict[int, tuple[float, ...]] = {",
    ]
    for street in (1, 2, 3):
        lines.append(f"    {street}: (")
        lines += [f"        {e!r}," for e in edges[street]]
        lines.append("    ),")
    lines += ["}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=os.cpu_count() or 1)
    parser.add_argument("--save-turns", type=Path, default=None,
                        help="also write every turn table (~30 MB .npz) for EHSTables.load_turns")
    args = parser.parse_args()
    tables = fill_tables(args.workers)
    if args.save_turns is not None:
        tables.save_turns(args.save_turns)
        print(f"wrote {args.save_turns} ({args.save_turns.stat().st_size / 1e6:.1f} MB)")
    write_module({street: street_edges(tables, street) for street in (1, 2, 3)})


if __name__ == "__main__":
    main()
